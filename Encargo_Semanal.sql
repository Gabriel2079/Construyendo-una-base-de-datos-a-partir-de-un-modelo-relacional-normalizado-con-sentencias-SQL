-- 1. Eliminar columna costo_total de MANTENCION
ALTER TABLE MANTENCION DROP COLUMN costo_total;

-- 2. Cambiar PK de MANTENCION a compuesta (num_mantencion, cod_sucursal) y ajustar FK en DETALLE_SERVICIO
-- A. Eliminar FK dependiente en DETALLE_SERVICIO
ALTER TABLE DETALLE_SERVICIO DROP CONSTRAINT DET_SERV_FK_MANTENCION;

-- B. Reemplazar PK de MANTENCION
ALTER TABLE MANTENCION DROP CONSTRAINT MANTENCION_PK;
